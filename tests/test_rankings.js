const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync('public/app.js','utf8');
const cut=src.indexOf("for(const id of ['search'");
assert(cut>0,'No se encontró el inicio del frontend');
const context={document:{},URL};
vm.runInNewContext(src.slice(0,cut)+"\nthis.rankTest={state,metric,metricDesc,rebuildRankings,allowedByRanking};",context);
const {state,metric,metricDesc,rebuildRankings,allowedByRanking}=context.rankTest;
state.all=JSON.parse(fs.readFileSync('public/catalog.json','utf8')).firmwares;
rebuildRankings();
const sloop=state.all.find(f=>f.id==='sloop');
assert(sloop&&sloop.installs>1000&&sloop.stars>50);
assert(allowedByRanking(sloop,'installs_top10'));
assert(allowedByRanking(sloop,'stars_top10'));
assert.equal(state.all.filter(f=>allowedByRanking(f,'installs_top10')).length,10);
assert.equal(state.all.filter(f=>allowedByRanking(f,'stars_top25')).length,25);
assert.equal(metric({installs:null},'installs'),null);
assert.equal(metric({installs:0},'installs'),0);
assert.equal(state.all.sort((a,b)=>metricDesc(a,b,'installs'))[0].id,'sloop');
console.log('OK: ranking JS y métricas.');
