// Pruebas deterministas del filtro temporal (sin navegador ni red).
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync('public/app.js','utf8');
const limit=src.indexOf("for(const id of ['search'");
assert(limit>0,'No se encontró el inicio del código de interfaz');
const context={document:{},URL,Date};
vm.runInNewContext(src.slice(0,limit)+'\nthis.dates={dateNumber,dateMatches,dateOrder,isReversedRange};',context);
const {dateNumber,dateMatches,dateOrder,isReversedRange}=context.dates;
const today=new Date(2026,10,21,12,0,0);
const record=date=>({date,name:'Firmware'});
assert.equal(dateNumber('2026-11-21'),Date.UTC(2026,10,21));
assert.equal(dateNumber('2026-02-30'),null);
assert.equal(dateNumber('2026-2-01'),null);
assert.equal(dateNumber(''),null);
assert.equal(dateMatches(record('2026-11-21'),'7','','',today),true);
assert.equal(dateMatches(record('2026-11-15'),'7','','',today),true);
assert.equal(dateMatches(record('2026-11-14'),'7','','',today),false);
assert.equal(dateMatches(record('2026-11-22'),'7','','',today),false);
assert.equal(dateMatches(record('2026-10-22'),'30','','',today),true);
assert.equal(dateMatches(record('2026-10-21'),'30','','',today),false);
assert.equal(dateMatches(record('2026-11-01'),'custom','2026-11-01','2026-11-15',today),true);
assert.equal(dateMatches(record('2026-11-15'),'custom','2026-11-01','2026-11-15',today),true);
assert.equal(dateMatches(record('2026-11-16'),'custom','2026-11-01','2026-11-15',today),false);
assert.equal(dateMatches(record('2026-11-15'),'custom','','2026-11-15',today),true);
assert.equal(dateMatches(record('2026-11-15'),'custom','2026-11-16','',today),false);
assert.equal(dateMatches(record(''),'undated','','',today),true);
assert.equal(dateMatches(record(''),'7','','',today),false);
assert.equal(dateMatches(record(''),'all','','',today),true);
assert.equal(dateMatches(record(''),'custom','','',today),true);
assert.equal(isReversedRange('2026-11-20','2026-11-01'),true);
assert.equal(isReversedRange('2026-11-01','2026-11-20'),false);
const all=[record(''),record('2026-11-15'),record('2026-10-03')];
assert.equal(all.sort((a,b)=>dateOrder(a,b,false))[0].date,'2026-11-15');
assert.equal(all.sort((a,b)=>dateOrder(a,b,true))[0].date,'2026-10-03');
assert.equal(all[all.length-1].date,'');
const html=fs.readFileSync('public/index.html','utf8');
for(const id of ['datePreset','dateFrom','dateTo','dateRange','dateHint'])assert(html.includes('id="'+id+'"'),'Falta control '+id);
const catalog=JSON.parse(fs.readFileSync('public/catalog.json','utf8'));
assert(catalog.firmwares.some(f=>f.date));
console.log('Filtros temporales: pruebas aprobadas.');
